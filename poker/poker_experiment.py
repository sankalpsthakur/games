def train_and_evaluate(
    algorithm_name: str,
    total_timesteps: int,
    log_dir: str,
    enable_video: bool = False,
):
    """
    Train a model of the specified algorithm on KuhnPokerEnv.
    Logs training metrics (TensorBoard) and records videos.
    """
    env = create_kuhn_poker_env()
    if enable_video:
        try:
            env = RecordVideo(env, video_folder=log_dir, episode_trigger=lambda ep: True)
        except Exception as exc:
            print(f"Skipping video recording for {algorithm_name}: {exc}")

    if algorithm_name == "PPO":
        model = PPO("MlpPolicy", env, verbose=1, tensorboard_log=log_dir)
    elif algorithm_name == "A2C":
        model = A2C("MlpPolicy", env, verbose=1, tensorboard_log=log_dir)
    elif algorithm_name == "DQN":
        model = DQN("MlpPolicy", env, verbose=1, tensorboard_log=log_dir)
    elif algorithm_name == "GRPO":
        model = GRPO("MlpPolicy", env, verbose=1, tensorboard_log=log_dir, grad_reg_coeff=0.01)
    else:
        raise ValueError(f"Unsupported algorithm name: {algorithm_name}")

    model.learn(total_timesteps=total_timesteps)
    mean_reward, std_reward = evaluate_policy(model, env, n_eval_episodes=100)
    print(f"{algorithm_name} evaluation: mean_reward = {mean_reward:.2f} ± {std_reward:.2f}")
    return model

