# 1. Define the Simple Kuhn Poker Environment using a Dict Observation Space
# =============================================================================

class KuhnPokerEnv(gym.Env):
    """
    Kuhn Poker Environment.

    There are three cards (0 = Jack, 1 = Queen, 2 = King). In each episode:
      - Both players ante 1 chip.
      - The agent (Player 1) receives one card and must choose:
            0: Check, 1: Bet.
      - If the agent bets, the opponent responds with a fixed strategy:
            * King (2): always call.
            * Queen (1): call with 50% chance, otherwise fold.
            * Jack (0): always fold.
          → Call leads to showdown (reward ±2); fold gives +1.
      - If the agent checks, the opponent then:
            * King (2): bets.
            * Queen (1): bets with 50% chance, otherwise checks.
            * Jack (0): checks.
          → If check, showdown gives ±1; if bet, the agent chooses:
                0: Fold (–1), or 1: Call (showdown ±2).

    Observations:
      A dictionary with:
         "card": Discrete(3) (the agent's card)
         "phase": Discrete(2) (0 for initial decision, 1 for response)
    """
    metadata = {"render_modes": ["human"], "render_fps": 4}

    def __init__(self) -> None:
        super().__init__()
        self.observation_space = spaces.Dict({
            "card": spaces.Discrete(3),
            "phase": spaces.Discrete(2)
        })
        # Action space: two actions. In phase 0: 0 = Check, 1 = Bet.
        # In phase 1: 0 = Fold, 1 = Call.
        self.action_space = spaces.Discrete(2)
        self.agent_card: int = 0
        self.opponent_card: int = 0
        self.phase: int = 0
        self.last_opponent_action: str = ""
        self.reset()

    def reset(
        self,
        *,
        seed: Optional[int] = None,
        options: Optional[Dict[str, Any]] = None,
    ) -> Tuple[Dict[str, Any], Dict[str, Any]]:
        super().reset(seed=seed)
        deck = [0, 1, 2]
        random.shuffle(deck)
        self.agent_card = deck[0]
        self.opponent_card = deck[1]
        self.phase = 0  # 0: initial decision; 1: responding after opponent bet.
        self.last_opponent_action = ""
        return self._get_obs(), {}

    def _get_obs(self) -> Dict[str, Any]:
        return {"card": self.agent_card, "phase": self.phase}

    def step(self, action: int) -> Tuple[Dict[str, Any], float, bool, bool, dict]:
        reward: int = 0
        terminated: bool = False
        truncated: bool = False
        info: dict = {}

        if self.phase == 0:
            # Agent's first decision: Check (0) or Bet (1)
            if action == 1:  # Bet
                opp_action = self._opponent_response_to_bet()
                self.last_opponent_action = opp_action
                if opp_action == 'call':
                    terminated = True
                    reward = 2 if self.agent_card > self.opponent_card else -2
                elif opp_action == 'fold':
                    terminated = True
                    reward = 1
                else:
                    raise ValueError("Unexpected opponent action.")
                return self._get_obs(), reward, terminated, truncated, info

            elif action == 0:  # Check
                opp_action = self._opponent_action_after_check()
                self.last_opponent_action = opp_action
                if opp_action == 'check':
                    terminated = True
                    reward = 1 if self.agent_card > self.opponent_card else -1
                    return self._get_obs(), reward, terminated, truncated, info
                elif opp_action == 'bet':
                    self.phase = 1
                    return self._get_obs(), reward, terminated, truncated, info
                else:
                    raise ValueError("Unexpected opponent action.")
            else:
                raise ValueError("Invalid action provided in phase 0.")

        elif self.phase == 1:
            # Agent's response to an opponent bet.
            if action == 0:  # Fold
                terminated = True
                reward = -1
            elif action == 1:  # Call
                terminated = True
                reward = 2 if self.agent_card > self.opponent_card else -2
            else:
                raise ValueError("Invalid action provided in phase 1.")
            return self._get_obs(), reward, terminated, truncated, info
        else:
            raise ValueError("Invalid game phase.")

    def _opponent_response_to_bet(self) -> str:
        if self.opponent_card == 2:  # King: always call.
            return 'call'
        elif self.opponent_card == 1:  # Queen: call 50% of the time.
            return 'call' if random.random() < 0.5 else 'fold'
        elif self.opponent_card == 0:  # Jack: always fold.
            return 'fold'
        else:
            raise ValueError("Invalid opponent card.")

    def _opponent_action_after_check(self) -> str:
        if self.opponent_card == 2:  # King: bet.
            return 'bet'
        elif self.opponent_card == 1:  # Queen: bet 50% of the time.
            return 'bet' if random.random() < 0.5 else 'check'
        elif self.opponent_card == 0:  # Jack: check.
            return 'check'
        else:
            raise ValueError("Invalid opponent card.")

    def render(self, mode: str = 'human') -> None:
        print(f"Agent card: {self.agent_card} | Opponent card: {self.opponent_card} | "
              f"Phase: {self.phase} | Last opponent action: {self.last_opponent_action}")

