# 7. Run a Few Inference Episodes to Observe the Learned Strategies
# =============================================================================

def run_inference(model, n_episodes: int = 5):
    """
    Run inference episodes on the environment using the provided model.
    """
    env = create_kuhn_poker_env()
    for episode in range(n_episodes):
        obs, _ = env.reset()
        done = False
        total_reward = 0
        print(f"\n--- Inference Episode {episode+1} ---")
        while not done:
            action, _ = model.predict(obs, deterministic=True)
            obs, reward, terminated, truncated, _ = env.step(action)
            done = terminated or truncated
            total_reward += reward
            env.render()
        print(f"Episode reward: {total_reward}")

print("\n=== Running inference using the PPO model ===")
run_inference(models["PPO"])

