def print_actor_critic_policy(model, model_name: str):
    """
    Print the action probabilities of actor-critic models (PPO, A2C, GRPO).
    """
    print(f"\nPolicy probabilities for {model_name}:")
    for card in range(3):
        # Create one-hot encoding for the card.
        card_onehot = np.zeros(3, dtype=np.float32)
        card_onehot[card] = 1.0
        for phase in [0, 1]:
            obs = np.concatenate([card_onehot, [float(phase)]])
            obs_tensor = torch.as_tensor(obs).float().unsqueeze(0)
            with torch.no_grad():
                latent_pi, _ = model.policy.mlp_extractor(obs_tensor)
                action_dist = model.policy._get_action_dist_from_latent(latent_pi)
                probs = action_dist.distribution.probs.cpu().numpy()[0]
            action_names = {0: "Check", 1: "Bet"} if phase == 0 else {0: "Fold", 1: "Call"}
            print(f"Card {card} ({'J' if card == 0 else 'Q' if card == 1 else 'K'}), Phase {phase}:")
            for action, prob in enumerate(probs):
                print(f"  {action_names[action]:5s}: {prob:.2f}")
    print("-" * 50)

def print_dqn_policy(model, model_name: str):
    """
    Print the Q-values (softmax probabilities) for the DQN model.
    """
    print(f"\nPolicy (Q–values as softmax probabilities) for {model_name}:")
    for card in range(3):
        card_onehot = np.zeros(3, dtype=np.float32)
        card_onehot[card] = 1.0
        for phase in [0, 1]:
            obs = np.concatenate([card_onehot, [float(phase)]])
            obs_tensor = torch.as_tensor(obs).float().unsqueeze(0)
            with torch.no_grad():
                q_values = model.q_net(obs_tensor)
                q_np = q_values.cpu().numpy()[0]
                exp_q = np.exp(q_np - np.max(q_np))
                probs = exp_q / np.sum(exp_q)
            action_names = {0: "Check", 1: "Bet"} if phase == 0 else {0: "Fold", 1: "Call"}
            print(f"Card {card} ({'J' if card == 0 else 'Q' if card == 1 else 'K'}), Phase {phase}:")
            for action, prob in enumerate(probs):
                print(f"  {action_names[action]:5s}: {prob:.2f}")
    print("-" * 50)

# Print the learned policy for each model.
for algo, model in models.items():
    if algo in ["PPO", "A2C", "GRPO"]:
        print_actor_critic_policy(model, algo)
    elif algo == "DQN":
        print_dqn_policy(model, algo)

