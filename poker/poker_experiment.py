class GRPO(PPO_Orig):
    """
    GRPO: A simplified variant of PPO with an additional gradient regularization term.
    """
    def __init__(self, *args, grad_reg_coeff: float = 0.01, **kwargs) -> None:
        super(GRPO, self).__init__(*args, **kwargs)
        self.grad_reg_coeff: float = grad_reg_coeff

    def train(self) -> None:
        """
        Simplified training loop: one pass over the rollout buffer with gradient regularization.
        """
        rollout_data = self.rollout_buffer.get(self.batch_size)
        for rollout_data_chunk in rollout_data:
            values, log_prob, entropy = self.policy.evaluate_actions(
                rollout_data_chunk.observations, rollout_data_chunk.actions
            )
            ratio = torch.exp(log_prob - rollout_data_chunk.old_log_prob)
            clip_range_val = self.clip_range(1) if callable(self.clip_range) else self.clip_range
            surr1 = ratio * rollout_data_chunk.advantages
            surr2 = torch.clamp(ratio, 1 - clip_range_val, 1 + clip_range_val) * rollout_data_chunk.advantages
            policy_loss = -torch.min(surr1, surr2).mean()

            # Compute gradient regularization term.
            grads = torch.autograd.grad(policy_loss, self.policy.parameters(), create_graph=True, allow_unused=True)
            grad_norm_sq = sum(g.pow(2).sum() for g in grads if g is not None)
            grad_reg = self.grad_reg_coeff * grad_norm_sq

            final_loss = policy_loss + grad_reg

            self.policy.optimizer.zero_grad()
            final_loss.backward()
            # Optional: Clip gradients for stability.
            torch.nn.utils.clip_grad_norm_(self.policy.parameters(), max_norm=0.5)
            self.policy.optimizer.step()
