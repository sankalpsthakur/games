# 2. Observation Wrapper to Convert Dict Observations to Flat Vectors
# =============================================================================

class DictToFlatWrapper(gym.ObservationWrapper):
    """
    Convert the dict observation (with keys "card" and "phase") into a flat vector.
    The card is represented as a one-hot vector (length 3) and phase is appended.
    Final observation shape: (4,)
    """
    def __init__(self, env: gym.Env) -> None:
        super().__init__(env)
        self.observation_space = spaces.Box(low=0, high=1, shape=(4,), dtype=np.float32)

    def observation(self, observation: Dict[str, Any]) -> np.ndarray:
        card = observation["card"]
        phase = observation["phase"]
        card_onehot = np.zeros(3, dtype=np.float32)
        card_onehot[card] = 1.0
        return np.concatenate([card_onehot, [float(phase)]])

def create_kuhn_poker_env() -> gym.Env:
    """
    Create the KuhnPokerEnv and wrap it to return flat (4-dimensional) observations.
    """
    env = KuhnPokerEnv()
    env = DictToFlatWrapper(env)
    return env

